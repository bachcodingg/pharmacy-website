export function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

export function formatVnd(amount, unit) {
  if (amount === null || amount === undefined) return null;
  const formatted = new Intl.NumberFormat('vi-VN').format(amount) + '₫';
  return unit ? `${formatted} / ${unit}` : formatted;
}

export function starRating(avg) {
  if (avg === null || avg === undefined) return '<span class="no-rating">No ratings yet</span>';
  const rounded = Math.round(avg);
  let html = '<span class="stars" aria-label="' + avg + ' out of 5">';
  for (let i = 1; i <= 5; i++) {
    html += `<span class="star ${i <= rounded ? 'star-filled' : ''}">${ICONS.star}</span>`;
  }
  html += `</span><span class="rating-number">${avg.toFixed(1)}</span>`;
  return html;
}
